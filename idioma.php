function id($cvar,$lCaixa=false,$repor='',$repor1='',$repor2='',$repor3='',$repor4=''){
    global $aidioma;
    global $idioma;
    for ($i=0;$i<count($aidioma);$i++){
        if ( (!$lCaixa?strtoupper($cvar):$cvar) == (!$lCaixa?strtoupper($aidioma[$i][0]):$aidioma[$i][0]) ){
            
            $cvar=$aidioma[$i][$idioma];
            if (!$cvar) $cvar=$aidioma[$i][0];
            continue;
        };
    }
    if ($repor){
        $cvar=str_replace("%s", $repor, $cvar);
    }
    if ($repor1){
        $cvar=str_replace("%s1", $repor1, $cvar);
    }
    if ($repor2){
        $cvar=str_replace("%s2", $repor2, $cvar);
    }
    if ($repor3){
        $cvar=str_replace("%s3", $repor3, $cvar);
    }
    if ($repor4){
        $cvar=str_replace("%s4", $repor4, $cvar);
    }
    
    return $cvar;
}

